/**
 * Отчёт мини-аппа о том, что он не запустился.
 *
 * Ручка единственная в приложении, которая работает без токена, и это не
 * недосмотр: она нужна ровно тогда, когда до входа дело не дошло. Если бандл
 * собран под систему новее той, что стоит у человека, браузер не выполняет из
 * модуля ни одной строки — ни токена, ни SDK, ни React. Живым остаётся только
 * встроенный в `index.html` скрипт, и его отчёт — единственный способ узнать,
 * у кого и на каком устройстве экран остался белым. Полтора месяца это было
 * невозможно узнать вовсе: сервер не писал в лог ни строки про отказы.
 *
 * Плата за отсутствие токена — жёсткие рамки: своё окно в лимитере, обрезанное
 * тело и обрезанные поля. Ответ всегда 204, даже на мусор: клиент, который сюда
 * пишет, уже сломан, и добавлять ему ошибку бессмысленно.
 */

/** Тела больше этого не читаем: отчёт о белом экране — три коротких поля. */
export const CLIENT_ERROR_BODY_MAX = 4_096;

export interface ClientErrorReport {
  reason?: unknown;
  userAgent?: unknown;
  url?: unknown;
}

function field(value: unknown, max: number): string {
  if (typeof value !== "string" || value.length === 0) return "—";
  return value.length > max ? `${value.slice(0, max)}…` : value;
}

/**
 * Одна строка лога: причина, устройство, адрес.
 *
 * Устройство здесь — главное поле, а не приписка. Именно `User-Agent` называет
 * версию iOS или Android, а версия системы и есть ответ на вопрос «почему у
 * этого человека не работает, а у соседа работает».
 */
export function describeClientError(report: ClientErrorReport): string {
  const source: ClientErrorReport = report && typeof report === "object" ? report : {};
  return [
    `мини-апп не запустился: ${field(source.reason, 400)}`,
    `устройство: ${field(source.userAgent, 300)}`,
    `адрес: ${field(source.url, 200)}`,
  ].join(" | ");
}
