-- `send_reminder` пролежал в таблице неиспользованным: кому напоминать, решала
-- эвристика по часам смены, а не эта колонка. Теперь решает колонка, и засеяна
-- она правилом «напоминаем про всё, кроме обычного дня» (`remindsByDefault`).
--
-- Часов для этого мало: дежурства идут те же 09:00–18:00, что и «День», и по
-- одним часам их не отличить. Отличает категория — дежурство не рутина, про
-- него напоминают всегда.
--
-- Это ОСОЗНАННОЕ изменение поведения, а не сохранение вчерашнего: четыре
-- дежурства 09:00–18:00 напоминаний не слали и начнут (его решение от
-- 2026-08-26), а «Вечер» слал при нуле в колонке и продолжит.
UPDATE `shift_templates`
SET `send_reminder` = CASE
  WHEN `category` <> 'shift' THEN 1
  WHEN `end` < `start` OR `start` < '09:00' OR `end` >= '20:00' THEN 1
  ELSE 0
END;
