-- `send_reminder` пролежал в таблице неиспользованным: кому напоминать, решала
-- эвристика `isReminderWorthy` по часам смены, а не эта колонка. Теперь решает
-- колонка — и её значения разошлись бы с тем, что команда получала вчера
-- (у «Вечера» стоял 0, хотя письма шли; у четырёх дежурств 09:00–18:00 стояла 1,
-- хотя писем не было). Пересев по той же эвристике делает день выкатки
-- незаметным: правила меняет админ галочкой, а не миграция за его спиной.
