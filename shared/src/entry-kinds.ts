import { countsForBalance, type EntryCategory } from "./category";

/** Ровно то, что списку видов нужно от пресета — не весь `TemplateDto`, чтобы
 *  правило не зависело от полей, которых оно не читает. */
export interface PresetLike {
  id: number;
  name: string;
  category: EntryCategory;
  sortOrder: number;
}

/**
 * Пресеты рабочих видов — одним списком, без деления на смены и дежурства.
 *
 * Его правка от 2026-08-21: «Смены и дежурства должны быть все вместе, не надо
 * их разделять». До неё обе формы записи спрашивали сперва категорию и только
 * потом показывали `templates.filter((t) => t.category === выбранная)` — то есть
 * увидеть дежурство, не сказав сперва «Дежурство», было нельзя, хотя в базе это
 * такой же пресет с часами и цветом, как «Утро».
 *
 * Категория при этом никуда не девается: она лежит В пресете, и форма просто
 * перестаёт спрашивать то, что уже знает.
 *
 * Отсутствия сюда не попадают: у них нет часов, они пишутся полосой, и в списке
 * «что ставим» они живут своей группой. Это деление он не называл — оно про
 * «человек работает» против «человека нет», а не про смены и дежурства.
 *
 * Порядок — `sortOrder`, тот же, каким пресеты идут в «Видах смен» и в балансе;
 * при равном порядке разводит имя, чтобы список не зависел от того, в каком
 * порядке их вернула база.
 */
export function workPresets<T extends PresetLike>(templates: readonly T[]): T[] {
  return templates
    .filter((t) => countsForBalance(t.category))
    .slice()
    .sort((a, b) => a.sortOrder - b.sortOrder || a.name.localeCompare(b.name, "ru"));
}

/**
 * Категории, которые можно поставить со своим временем.
 *
 * «Работа в выходной» здесь есть намеренно: без пресета её иначе не поставить
 * вовсе, а правило «только суббота и воскресенье» стережёт не форма, а сервер
 * (`categoryFitsDate`) — и стережёт одинаково, откуда бы запись ни пришла.
 */
export const CUSTOM_TIME_CATEGORIES: readonly EntryCategory[] = ["shift", "duty", "offsite", "weekend_work"];

/** Отсутствия — вторая группа списка «что ставим», в порядке частоты. */
export const ABSENCE_CATEGORIES: readonly EntryCategory[] = ["vacation", "sick_leave", "business_trip"];
