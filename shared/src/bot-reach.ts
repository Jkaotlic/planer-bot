/**
 * Кому бот сейчас не может написать ничего — ни напоминания, ни опроса, ни ЧП.
 *
 * Две причины, и обе админ чинит руками: без Telegram — отдать ссылку-приглашение,
 * заблокировал — попросить человека снова написать боту. Отписка от вечерних
 * напоминаний сюда не входит: остальное такому человеку доходит.
 *
 * Архивные не считаются: им бот молчит нарочно, и в счётчике «надо что-то
 * сделать» они были бы ложной тревогой.
 *
 * `botBlockedAt` необязателен: схема ответа его допускает отсутствующим, и
 * отсутствие значит «отметки нет», а не «неизвестно».
 */
export function cannotHearBot(e: { isActive: boolean; telegramUserId: number | null; botBlockedAt?: unknown }): boolean {
  if (!e.isActive) return false;
  return e.telegramUserId == null || Boolean(e.botBlockedAt);
}
