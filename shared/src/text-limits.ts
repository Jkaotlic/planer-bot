/**
 * Потолки длины для текстов, которые человек набирает в форме, а бот потом вставляет
 * в письмо в Telegram.
 *
 * Без потолка такой текст рвёт письмо: Telegram не принимает сообщение длиннее 4096
 * знаков, и рассылка «Нужен человек на выходной» или письмо об изменении графика
 * просто не доходит — а форма при этом отвечает «готово». Короткие потолки выбраны
 * под то, что реально пишут в поле, а не под предел Telegram: подпись и место — это
 * строка в сетке и в письме, заметка — пара предложений.
 *
 * Слот выходного и запись графика делят одни и те же потолки: назначение на слот
 * переписывает его название и место в запись `weekend_work`, и запись не должна
 * получить то, чего её собственная форма не приняла бы.
 *
 * Значения общие для сервера (zod/ручные проверки, 400 с этим же текстом) и для
 * `maxLength` на полях обеих морд.
 */
export const ENTRY_TITLE_MAX = 200;
export const ENTRY_LOCATION_MAX = 200;
export const ENTRY_NOTE_MAX = 1000;

/** «Название — не длиннее 200 знаков» — одна формулировка отказа на любое поле. */
export function tooLongText(label: string, max: number): string {
  return `${label} — не длиннее ${max} знаков`;
}

/**
 * Сбор: повод стоит в заголовке письма всей команде, свой текст — тело того же
 * письма. Вместе со ссылкой и строкой о сумме письмо остаётся под пределом Telegram.
 */
export const COLLECTION_TITLE_MAX = 80;
export const COLLECTION_TEXT_MAX = 3000;

/**
 * Имя сотрудника стоит почти в каждом письме бота — «Аня просит обменяться…»,
 * списки коллег в напоминании. Сотня знаков вмещает любое ФИО с запасом.
 */
export const EMPLOYEE_NAME_MAX = 100;

/**
 * Чек-лист: название и подпись пункта стоят строкой в списке и в сообщении дежурному,
 * пояснение уезжает в то же сообщение (пояснение — тот же 2000, что у багрепорта:
 * у Telegram предел 4096 на всё письмо вместе со списком пунктов). Ссылка на документ
 * — с запасом под длинные адреса облачных дисков.
 */
export const CHECKLIST_NAME_MAX = 120;
export const CHECKLIST_ITEM_TITLE_MAX = 200;
export const CHECKLIST_NOTE_MAX = 2000;
export const CHECKLIST_DOC_URL_MAX = 500;

/**
 * Потолок одного письма с запасом до лимита Telegram в 4096 знаков. Общий для всех
 * писем, которые склеивают строки по людям или сборам: заказ, итог опроса, «Сервисы»,
 * чек-лист дежурного (через `clampTelegramText`).
 */
export const TELEGRAM_TEXT_SAFE_MAX = 4000;

/**
 * Укорачивает письмо до `max`, срезая целые строки с конца и ставя вместо них
 * хвост `tail(N)` — «…и ещё N строк».
 *
 * Зачем: письмо длиннее 4096 знаков Telegram отвергает целиком, отказ выглядит
 * как «насовсем» (400), и рассылка молча гаснет до утра — так терялся чек-лист
 * дежурного (аудит 2026-10-26, H2). Обрезанное письмо, которое честно говорит,
 * сколько не вошло, лучше пропавшего.
 *
 * Строками, а не знаками: оборванный посреди пункт читается как опечатка, а не
 * как сокращение. Пустые строки скрытыми не считаются и перед хвостом не
 * остаются: «ещё 4 строки», из которых две — пустые разделители, обещали бы
 * текст, которого нет. Если даже первая строка длиннее предела, она режется по
 * знакам с «…», и считается скрытой — целиком она не показана.
 *
 * Результат всегда `≤ max`: это контракт, ради которого функция существует.
 */
export function clampTelegramText(
  text: string,
  tail: (hiddenLines: number) => string,
  max = TELEGRAM_TEXT_SAFE_MAX,
): string {
  if (text.length <= max) return text;
  const lines = text.split("\n");
  const hiddenFrom = (from: number) => lines.slice(from).filter((l) => l.trim() !== "").length;
  // Перебор с конца: строк — десятки, а арифметика длин ошибалась бы на
  // разделителях (тот же довод, что у `orderInviteText`).
  for (let keep = lines.length - 1; keep >= 1; keep -= 1) {
    const head = lines.slice(0, keep).join("\n").trimEnd();
    const hidden = hiddenFrom(keep);
    const out = hidden === 0 ? head : `${head}\n${tail(hidden)}`;
    if (out.length <= max) return out;
  }
  const end = tail(hiddenFrom(1) + 1);
  let room = max - end.length - 2; // «…» и перевод строки
  if (room <= 0) return end.slice(0, max);
  // Половинка суррогатной пары — битый UTF-16, и Telegram отверг бы уже
  // обрезанное письмо.
  const first = lines[0] ?? "";
  if (/[\uD800-\uDBFF]/.test(first.charAt(room - 1))) room -= 1;
  return `${first.slice(0, room)}…\n${end}`;
}

/** «1 строка» / «2 строки» / «5 строк» — для хвоста обрезанного письма. */
export function linesWord(count: number): string {
  const mod100 = count % 100;
  const mod10 = count % 10;
  if (mod100 >= 11 && mod100 <= 14) return `${count} строк`;
  if (mod10 === 1) return `${count} строка`;
  if (mod10 >= 2 && mod10 <= 4) return `${count} строки`;
  return `${count} строк`;
}
