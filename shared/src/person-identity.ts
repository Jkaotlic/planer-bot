/**
 * Как человек опознаётся в любом списке: две буквы и цвет.
 *
 * Одно правило на все четыре поверхности, где рисуются люди, — сетка консоли,
 * колонка баланса, «Работники» и «Команда» в мини-аппе. Раньше оно лежало двумя
 * одинаковыми копиями (`admin/src/lib/people.ts` и `miniapp/src/lib/people.ts`),
 * а зеркальные файлы в этом репозитории расходились уже трижды. Здесь
 * расхождение было бы особенно заметным: один и тот же человек читался бы
 * разным цветом на двух экранах.
 */

/** One or two initials from a full display name: "Смирнова Аня" -> "СА". */
export function initialsOf(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  const first = parts[0]?.[0] ?? "";
  const second = parts[1]?.[0] ?? "";
  return (first + second).toUpperCase();
}

export interface PersonPalette {
  readonly bg: string;
  readonly fg: string;
}

/**
 * Фиксированные, не зависящие от темы цвета аватарок.
 *
 * Не от темы, чтобы цвет человека не менялся при переключении светлой и тёмной:
 * он опознавательный знак, а не оформление.
 *
 * Первые пять — те же, что были в макетах и в обеих консолях до расширения
 * палитры, и стоят на прежних местах намеренно: людям с id 1..5 цвет менять не
 * за что. Остальные семь добавлены потому, что пяти на команду из двух с лишним
 * десятков человек не хватало — каждый цвет носили пятеро, соседние строки
 * списка сливались, и цвет не опознавал никого.
 *
 * Все двенадцать держат контраст с белым текстом не ниже 4.5:1 — это проверяет
 * тест, а не глаз: следующий цвет добавят, а глазами проверять не станут.
 * Было 3:1, и инициалы на синем (3.31), оранжевом, зелёном и бирюзовом в
 * светлой сетке консоли читались хуже обычного текста. Четыре первых цвета и
 * ещё три затемнены в том же оттенке (меняется только светлота), так что
 * человека по-прежнему узнают по цвету.
 */
export const AVATAR_PALETTE: readonly PersonPalette[] = [
  { bg: "#1475D6", fg: "#FFFFFF" },
  // Оранжевый затемнялся уже раз (с #E8890C), теперь ещё: тот же оттенок.
  { bg: "#AC6408", fg: "#FFFFFF" },
  { bg: "#228740", fg: "#FFFFFF" },
  { bg: "#8A55E0", fg: "#FFFFFF" },
  { bg: "#0D828E", fg: "#FFFFFF" },
  { bg: "#D14056", fg: "#FFFFFF" },
  { bg: "#5B6ABF", fg: "#FFFFFF" },
  // Охристый, а не просто темнее прежнего: затемнённый #B0700A (#A46809)
  // почти совпал бы с оранжевым выше, а соседние цвета должны различаться.
  { bg: "#8A6508", fg: "#FFFFFF" },
  { bg: "#1E8474", fg: "#FFFFFF" },
  { bg: "#A34FA8", fg: "#FFFFFF" },
  { bg: "#4A7C2F", fg: "#FFFFFF" },
  { bg: "#C05621", fg: "#FFFFFF" },
];

/**
 * Цвет человека — по id, а не по имени.
 *
 * По id, потому что имя правят: переименование не должно перекрашивать
 * человека, к цвету которого уже привыкли. Простой остаток от деления, а не
 * хеш: подряд идущие в ростере люди получают подряд идущие цвета, и соседние
 * строки списка гарантированно разные — ровно то, ради чего цвет здесь и есть.
 */
export function personPalette(employeeId: number | null): PersonPalette {
  const id = employeeId ?? 1;
  const index = (((id - 1) % AVATAR_PALETTE.length) + AVATAR_PALETTE.length) % AVATAR_PALETTE.length;
  return AVATAR_PALETTE[index] ?? AVATAR_PALETTE[0]!;
}
