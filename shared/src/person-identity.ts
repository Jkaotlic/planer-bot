/**
 * Цвет человека — по id, а не по имени.
 *
 * По id, потому что имя правят: переименование не должно перекрашивать
 * человека, к цвету которого уже привыкли. Простой остаток от деления, а не
 * хеш: подряд идущие в ростере люди получают подряд идущие цвета, и соседние
 * строки списка гарантированно разные — ровно то, ради чего цвет здесь и есть.
 */
export function personPalette(employeeId: number | null): PersonPalette {
  const id = employeeId ?? 1;
  const index = (((id - 1) % AVATAR_PALETTE.length) + AVATAR_PALETTE.length) % AVATAR_PALETTE.length;
  return AVATAR_PALETTE[index] ?? AVATAR_PALETTE[0]!;
}
