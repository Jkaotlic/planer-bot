/**
 * Как человек опознаётся в любом списке: две буквы и цвет.
 *
 * Одно правило на все четыре поверхности, где рисуются люди, — сетка консоли,
 * колонка баланса, «Работники» и «Команда» в мини-аппе. Раньше оно лежало двумя
 * одинаковыми копиями (`admin/src/lib/people.ts` и `miniapp/src/lib/people.ts`),
 * а зеркальные файлы в этом репозитории расходились уже трижды. Здесь
 * расхождение было бы особенно заметным: один и тот же человек читался бы
 * разным цветом на двух экранах.
 */

/** One or two initials from a full display name: "Смирнова Аня" -> "СА". */
export function initialsOf(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  const first = parts[0]?.[0] ?? "";
  const second = parts[1]?.[0] ?? "";
  return (first + second).toUpperCase();
}

export interface PersonPalette {
  readonly bg: string;
  readonly fg: string;
}

/**
 * Фиксированные, не зависящие от темы цвета аватарок.
 *
 * Не от темы, чтобы цвет человека не менялся при переключении светлой и тёмной:
 * он опознавательный знак, а не оформление.
 *
 * Первые пять — те же, что были в макетах и в обеих консолях до расширения
 * палитры, и стоят на прежних местах намеренно: людям с id 1..5 цвет менять не
 * за что. Остальные семь добавлены потому, что пяти на команду из двух с лишним
 * десятков человек не хватало — каждый цвет носили пятеро, соседние строки
 * списка сливались, и цвет не опознавал никого.
 *
 * Все двенадцать держат контраст с белым текстом не ниже 3:1 — это проверяет
 * тест, а не глаз: следующий цвет добавят, а глазами проверять не станут.
 */
